# ADME app
import streamlit as st
import pandas as pd
from rdkit import Chem
from rdkit.Chem import Descriptors, Crippen, Lipinski

st.set_page_config(page_title="ADME Predictor", layout="centered")

st.title("ADME Predictor")
st.write("Predict physicochemical properties from a SMILES string using RDKit.")

# -----------------------------
# Helper functions
# -----------------------------

def calculate_properties(smiles):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None

    mw = Descriptors.MolWt(mol)
    logp = Crippen.MolLogP(mol)
    hbd = Lipinski.NumHDonors(mol)
    hba = Lipinski.NumHAcceptors(mol)

    # ESOL (Delaney) solubility model
    # logS = 0.16 - 1.5*logP - 0.01*(MW - 40) + 0.66*RB - 0.66*AP
    rb = Lipinski.NumRotatableBonds(mol)
    ap = Lipinski.FractionCSP3(mol)
    logS = 0.16 - 1.5*logp - 0.01 * (mw - 40) + 0.66 * rb - 0.66 * ap

    return {
        "Molecular Weight (MW)": round(mw, 2),
        "LogP": round(logp, 2),
        "H-Bond Donors": hbd,
        "H-Bond Acceptors": hba,
        "LogS (ESOL)": round(logS, 2)
    }

# -----------------------------
# User input
# -----------------------------

smiles_input = st.text_input(
    "Enter SMILES string",
    value="CC(=O)OC1=CC=CC=C1C(=O)O"  # Aspirin example
)

if st.button("Predict Properties"):
    results = calculate_properties(smiles_input)

    if results is None:
        st.error("Invalid SMILES string. Please check and try again.")
    else:
        st.success("Prediction Successful")
        df = pd.DataFrame(results.items(), columns=["Property", "Value"])
        st.table(df)

        st.markdown("### Interpretation")
        st.write("- **MW < 500**: Generally favorable for oral drugs")
        st.write("- **LogP 1–5**: Balanced lipophilicity")
        st.write("- **HBD ≤ 5, HBA ≤ 10**: Lipinski's Rule of Five")
        st.write("- **LogS**: More negative values indicate lower solubility")

st.markdown("---")
st.caption("Educational tool for ADME/cheminformatics training")